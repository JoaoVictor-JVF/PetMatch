package petmatch;

public class Animal {
    String nome;
    int atividade;
    int espaco;
    int exercicio;
    int interacao;
    int independencia;
    int ficarSozinho;
    int cuidado;
    int custo;
    int treinamento;

    public Animal(String nome, int atividade, int espaco, int exercicio,
                  int interacao, int independencia, int ficarSozinho,
                  int cuidado, int custo, int treinamento) {
        this.nome = nome;
        this.atividade = atividade;
        this.espaco = espaco;
        this.exercicio = exercicio;
        this.interacao = interacao;
        this.independencia = independencia;
        this.ficarSozinho = ficarSozinho;
        this.cuidado = cuidado;
        this.custo = custo;
        this.treinamento = treinamento;
    }
}
